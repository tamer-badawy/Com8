class Chip8
{
public:
    uint8_t registers[16];
    uint8_t memory[4096];
    uint16_t index_reg;
    uint16_t pc;

    uint16_t stack[16];
    uint8_t sp;

    uint8_t keypad[16];
    uint32_t video[64 * 32];

    uint8_t delayTimer;
    uint8_t delaySound;

    Chip8();

    void Reset();
    bool LoadChip(const std::string &filename);
    void Cycle();
    void UpdateTimers();

private:
    std::mt19937 gen;
    std::uniform_int_distribution<uint8_t> rand;
};

